export function textDots(value: string): Array<[number, number]> {
  const dots: Array<[number, number]> = [];
  let x = 0;
  let y = 0;
  const clean = value.normalize("NFD").replace(/\p{M}/gu, "").toUpperCase();
  for (const char of clean) {
    if (char === "\n") {
      x = 0;
      y += 6;
      continue;
    }
    const glyph = FONT[char];
    if (!glyph) {
      x += 4;
      continue;
    }
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx += 1) {
        if (row[gx] === "1") dots.push([x + gx, y + gy]);
      }
    });
    x += 4;
  }
  return dots;
}
